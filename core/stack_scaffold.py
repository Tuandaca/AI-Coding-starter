COMMON_IGNORES = [
    "# Runtime-derived adapter output (non-authoritative, reversible)",
    ".codex/",
    ".opencode/",
    ".claude/",
    ".cursor/",
    ".agent/",
    "# Staging leftovers",
    ".staging-*",
    ".runtime-manifest.json",
]


def write_gitignore(dest_dir: Path | str, bundle_id: str) -> Path:
    """Write a stack-aware ``.gitignore``.

    Never ignores the canonical state (``.ai-coding-starter/``) or the
    portable workspace (``.ai-workspace/``); these travel with the project.
    """
    dest = Path(dest_dir)
    lines: list[str] = []
    lines.extend(GITIGNORE_TEMPLATES.get(bundle_id, []))
    if lines:
        lines.append("")
    lines.extend(COMMON_IGNORES)
    path = dest / ".gitignore"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


