# Stack bundle -> template files. Only react-static is bundled by default;
# other bundles resolve to an empty scaffold (no code generated).
BUNDLE_TEMPLATES: dict[str, dict[str, str]] = {
    "react-static": {**REACT_STATIC_FILES, **REACT_STATIC_CONFIG_FILES},
}


def scaffold_files(bundle_id: str, project_name: str) -> dict[str, str]:
    """Return the scaffold file map for a bundle, with project name substituted."""
    templates = BUNDLE_TEMPLATES.get(bundle_id, {})
    out: dict[str, str] = {}
    for rel_path, content in templates.items():
        out[rel_path] = content.replace("{{project_name}}", project_name)
    return out


def scaffold_stack(dest_dir: Path | str, bundle_id: str, project_name: str) -> list[Path]:
    """Write a stack bundle's scaffold files into ``dest_dir``.

    Returns the list of written paths. Empty for bundles without a template.
    """
    dest = Path(dest_dir)
    files = scaffold_files(bundle_id, project_name)
    written: list[Path] = []
    for rel_path, content in files.items():
        target = dest / rel_path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        written.append(target)
    return written


