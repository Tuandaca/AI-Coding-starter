def write_project_readme(
    dest_dir: Path | str,
    project_name: str,
    project_type: str,
    capabilities: list[str],
    stack_bundle: str,
    runtime_id: str,
    instructions_dir: str = ".ai-coding-starter",
) -> Path:
    """Write the generated project's own ``README.md``.

    Not a copy of the starter's README; it documents the generated project.
    The stack scaffold support level is displayed honestly: a ``metadata-only``
    bundle means no application source code was scaffolded.
    """
    dest = Path(dest_dir)
    caps = ", ".join(capabilities) if capabilities else "None"
    support = scaffold_support_for(stack_bundle)
    if support == "full":
        support_line = (
            "- **Stack scaffold support**: full — functional application "
            "source code was scaffolded from offline templates."
        )
    else:
        support_line = (
            "- **Stack scaffold support**: metadata-only — no application "
            "source code was scaffolded for this bundle. The generated project "
            "contains canonical AI-Coding-starter state and portable resources "
            "only; application source code was NOT created and must be added "
            "by the user (or by a future scaffold roadmap bundle)."
        )
    lines = [
        f"# {project_name}",
        "",
        "Generated by AI-Coding-starter v2.1.1 — Portable Workspace & Resolver Hotfix.",
        "",
        "## Project",
        f"- **Project type**: {project_type}",
        f"- **Stack**: {stack_bundle}",
        f"- **Capabilities**: {caps}",
        f"- **Runtime**: {runtime_id}",
        support_line,
        f"- **Canonical state**: `{instructions_dir}/` (project.yaml, state.yaml, resources.lock)",
        f"- **Portable AI workspace**: `.ai-workspace/`",
        "",
        "## Getting Started",
        "",
        "### Install dependencies",
        "",
        "```bash",
        "npm install",
        "```",
        "",
        "### Run development server",
        "",
        "```bash",
        "npm run dev",
        "```",
        "",
        "### Build for production",
        "",
        "```bash",
        "npm run build",
        "```",
        "",
        "## AI-Coding-starter state",
        "",
        "- `.ai-coding-starter/project.yaml` — machine-authoritative project identity.",
        "- `.ai-coding-starter/state.yaml` — machine-authoritative workflow/session state.",
        "- `.ai-coding-starter/resources.lock` — resource/stack lock with provenance.",
        "",
        "These files travel with the project and are portable across AI coding runtimes.",
        "",
        "## Switching runtime",
        "",
        "From the starter repository, re-run the creator against this project:",
        "",
        "```bash",
        "python new_project.py --switch-runtime codex --project .",
        "python new_project.py --switch-runtime antigravity --project .",
        "python new_project.py --switch-runtime opencode --project .",
        "python new_project.py --switch-runtime claude-code --project .",
        "python new_project.py --switch-runtime cursor --project .",
        "python new_project.py --switch-runtime portable --project .",
        "```",
        "",
        "Canonical state and the portable workspace are preserved across switches;",
        "only runtime-owned derived files change.",
        "",
    ]
    path = dest / "README.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path